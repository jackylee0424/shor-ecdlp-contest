#!/usr/bin/env python3
"""Generate the exact rational 25/32 hddivstep invariant polygon.

The construction follows the stable-hull decomposition in
sipa/safegcd-bounds/genproofhd.md, but uses the deliberately weaker rational
rate r=25/32.  All arithmetic is Fraction arithmetic.  Starting from the
central l1 diamond, closure under the five reduced transition matrices reaches
a fixed 10-vertex polygon after two rounds.

Run from the lab root:
    python3 workspace/divstep_hull.py

This rewrites workspace/DivstepHullData.lean and prints a reproducibility
receipt.  No floating-point arithmetic is used.
"""

from __future__ import annotations

from fractions import Fraction as Q
from pathlib import Path


Point = tuple[Q, Q]
Matrix = tuple[tuple[Q, Q], tuple[Q, Q]]


def mm(a: Matrix, b: Matrix) -> Matrix:
    return tuple(
        tuple(sum((a[i][k] * b[k][j] for k in range(2)), Q(0)) for j in range(2))
        for i in range(2)
    )  # type: ignore[return-value]


def mv(a: Matrix, p: Point) -> Point:
    return (
        a[0][0] * p[0] + a[0][1] * p[1],
        a[1][0] * p[0] + a[1][1] * p[1],
    )


def scale(c: Q, a: Matrix) -> Matrix:
    return tuple(tuple(c * x for x in row) for row in a)  # type: ignore[return-value]


def inverse(a: Matrix) -> Matrix:
    det = a[0][0] * a[1][1] - a[0][1] * a[1][0]
    assert det
    return (
        (a[1][1] / det, -a[0][1] / det),
        (-a[1][0] / det, a[0][0] / det),
    )


def cross(o: Point, a: Point, b: Point) -> Q:
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


def convex_hull(points: list[Point]) -> list[Point]:
    ps = sorted(set(points))
    if len(ps) <= 1:
        return ps
    lower: list[Point] = []
    for p in ps:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    upper: list[Point] = []
    for p in reversed(ps):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return lower[:-1] + upper[:-1]


R = Q(25, 32)
S: Matrix = ((Q(0), Q(1)), (-Q(1, 2), Q(1, 2)))
E: Matrix = ((Q(1), Q(0)), (Q(0), Q(1, 2)))
N: Matrix = ((Q(1), Q(0)), (Q(1, 2), Q(1, 2)))


def dmat(n: int) -> Matrix:
    return ((Q(1), Q(0)), (Q(0), Q(1, 2**n)))


REDUCED: list[tuple[str, Matrix]] = [
    ("swap", scale(1 / R, S)),
    ("neg1Even", scale(1 / R**3, mm(mm(E, S), dmat(1)))),
    ("neg1Odd", scale(1 / R**3, mm(mm(N, S), dmat(1)))),
    (
        "tailEven",
        scale(1 / R**2, mm(mm(mm(inverse(mm(S, dmat(1))), E), S), dmat(2))),
    ),
    (
        "tailOdd",
        scale(1 / R**2, mm(mm(mm(inverse(mm(S, dmat(1))), N), S), dmat(2))),
    ),
]


def close_polygon() -> tuple[list[Point], int]:
    vertices = convex_hull([(Q(1), Q(0)), (-Q(1), Q(0)), (Q(0), Q(1)), (Q(0), -Q(1))])
    rounds = 0
    while True:
        nxt = convex_hull(vertices + [mv(a, p) for _, a in REDUCED for p in vertices])
        if nxt == vertices:
            return vertices, rounds
        vertices = nxt
        rounds += 1


def facets(vertices: list[Point]) -> list[Point]:
    """Outward facet functionals l with l(x)<=1 on the polygon."""
    out: list[Point] = []
    for a, b in zip(vertices, vertices[1:] + vertices[:1]):
        nx, ny = b[1] - a[1], a[0] - b[0]
        c = nx * a[0] + ny * a[1]
        assert c > 0
        out.append((nx / c, ny / c))
    return out


def lean_q(x: Q) -> str:
    if x.denominator == 1:
        return str(x.numerator)
    return f"({x.numerator} / {x.denominator} : ℚ)"


def emit(vertices: list[Point], normals: list[Point], rounds: int) -> str:
    positive_normals = normals[: len(normals) // 2]
    lines = [
        "/- This file is generated by workspace/divstep_hull.py. -/",
        "import Mathlib.Data.Rat.Defs",
        "",
        "namespace ShorECDLP.DivstepHullData",
        "",
        f"def closureRounds : Nat := {rounds}",
        f"def vertexCount : Nat := {len(vertices)}",
        f"def facetPairCount : Nat := {len(positive_normals)}",
        "",
    ]
    for i, (x, y) in enumerate(vertices):
        lines.append(f"def v{i} : ℚ × ℚ := ({lean_q(x)}, {lean_q(y)})")
    lines.append("")
    for i, (x, y) in enumerate(positive_normals):
        lines.append(f"def n{i} : ℚ × ℚ := ({lean_q(x)}, {lean_q(y)})")
    lines += [
        "",
        "def vertices : List (ℚ × ℚ) := [" + ", ".join(f"v{i}" for i in range(len(vertices))) + "]",
        "def normals : List (ℚ × ℚ) := [" + ", ".join(f"n{i}" for i in range(len(positive_normals))) + "]",
        "",
    ]
    for name, a in REDUCED:
        entries = [lean_q(a[i][j]) for i in range(2) for j in range(2)]
        lines.append(
            f"def {name} : (ℚ × ℚ) × (ℚ × ℚ) := "
            f"((({entries[0]}), ({entries[1]})), (({entries[2]}), ({entries[3]})))"
        )
    lines += ["", "end ShorECDLP.DivstepHullData", ""]
    return "\n".join(lines)


def main() -> None:
    vertices, rounds = close_polygon()
    normals = facets(vertices)
    assert len(vertices) == 10 and rounds == 2
    assert all((-x, -y) in vertices for x, y in vertices)
    for _, a in REDUCED:
        for p in vertices:
            q = mv(a, p)
            assert all(nx * q[0] + ny * q[1] <= 1 for nx, ny in normals)
    target = Path(__file__).with_name("DivstepHullData.lean")
    target.write_text(emit(vertices, normals, rounds), encoding="utf-8", newline="\n")
    max_bits = max(
        max(abs(x.numerator).bit_length(), x.denominator.bit_length())
        for p in vertices + normals
        for x in p
    )
    print(f"rate={R} closure_rounds={rounds} vertices={len(vertices)} facet_pairs={len(normals)//2}")
    print(f"max_coordinate_bits={max_bits} output={target}")


if __name__ == "__main__":
    main()
